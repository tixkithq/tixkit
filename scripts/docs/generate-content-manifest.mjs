import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { adoptionPathsForRoute } from '../../packages/docs-core/dist/index.js';
import { loadPublicDocuments } from './lib/content.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const output = resolve(root, 'apps/docs/src/generated/content-manifest.ts');
const searchOutput = resolve(root, 'apps/docs/public/search-index.json');
const checkOnly = process.argv.includes('--check');
const sdkGuideSections = JSON.parse(
  readFileSync(resolve(root, 'docs/sdk-guide-sections.json'), 'utf8'),
);
const { documents, errors } = loadPublicDocuments(root);
if (errors.length > 0) throw new Error(`Cannot generate content manifest:\n${errors.join('\n')}`);

function expandedDocument(document) {
  const match = document.body.match(/<SdkGuide\s+sdkId="([^"]+)"\s*\/>/);
  if (!match) return document;
  const headings = [
    ...document.headings,
    ...sdkGuideSections.map((section) => ({ id: section.id, text: section.title, level: 2 })),
  ];
  return {
    ...document,
    headings,
    body: `${document.body}\n${match[1]} ${sdkGuideSections.map((section) => `${section.title} ${section.searchText}`).join(' ')}`,
  };
}

const expandedDocuments = documents.map(expandedDocument);

function emitGenerated(path, content) {
  if (checkOnly) {
    const current = readFileSync(path, 'utf8');
    if (current !== content) {
      throw new Error(`Generated documentation artifact is stale: ${relative(root, path)}`);
    }
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, 'utf8');
}

const records = expandedDocuments.map((document) => {
  const importPath = relative(dirname(output), resolve(root, document.path)).split(sep).join('/');
  return `  ${JSON.stringify(document.route)}: {
    sourcePath: ${JSON.stringify(document.path)},
    frontmatter: ${JSON.stringify(document.frontmatter)},
    headings: ${JSON.stringify(document.headings)},
    load: () => import(${JSON.stringify(importPath.startsWith('.') ? importPath : `./${importPath}`)}),
  },`;
});

const source = `/* This file is generated by scripts/docs/generate-content-manifest.mjs. */
import type { ComponentType } from 'react';
import type { PublicDocFrontmatter } from '@tixkit/docs-core';

export interface PublicDocModule {
  default: ComponentType;
  frontmatter: PublicDocFrontmatter;
}

export interface PublicDocManifestEntry {
  sourcePath: string;
  frontmatter: PublicDocFrontmatter;
  headings: readonly { id: string; text: string; level: 2 | 3 }[];
  load: () => Promise<PublicDocModule>;
}

export const contentManifest: Record<string, PublicDocManifestEntry> = {
${records.join('\n')}
};

export type PublicDocRoute = string;
`;

emitGenerated(output, source);
const searchRecords = expandedDocuments.map((document) => ({
  url: document.route,
  title: document.frontmatter.title,
  description: document.frontmatter.description,
  headings: document.headings,
  body: document.body
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/[#>*_`[\]()!-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim(),
  audience: document.frontmatter.audience,
  productArea: document.frontmatter.product_area,
  contentType: document.frontmatter.content_type,
  status: document.frontmatter.status,
  keywords: document.frontmatter.keywords ?? [],
  adoptionPaths: adoptionPathsForRoute(document.route, document.frontmatter.adoption_paths),
}));
emitGenerated(searchOutput, `${JSON.stringify(searchRecords, null, 2)}\n`);
console.log(
  `${checkOnly ? 'Validated' : 'Generated'} ${documents.length} documentation content entries and search records`,
);
